    /// Rebuilt as tick points, 30 s apart. `breathSD` is the spread measured
    /// inside each five-minute bucket, replayed as jitter so the reconstructed
    /// ticks carry the variability the real recording had rather than a
    /// suspiciously flat line.
    static func points() -> [MetricsHistoryPoint] {
        var comps = DateComponents(year: 2026, month: 8, day: 18)
        comps.hour = 12
        comps.minute = 30
        let start = Calendar.current.date(from: comps)!
        var out: [MetricsHistoryPoint] = []
        for (mins, hr, motion, breath, breathSD, coherence, lfHF, sdnn, rmssd) in samples {
            for tick in 0..<10 {
                let t = start.addingTimeInterval(Double(mins) * 60 + Double(tick) * 30)
                // Deterministic alternation, so the spread is reproduced without
                // a random source the tests would have to seed.
                let jitter = breathSD * (tick % 2 == 0 ? 1 : -1)
                out.append(MetricsHistoryPoint(anchorTestTimestamp: t,
                                               meanBPM: hr, vti: log(rmssd),
                                               dc: 8, pip: 45, dfa1: 1.0,
                                               breathBPM: breath + jitter, motion: motion,
                                               signalQuality: 0.97,
                                               rrInvalidRate: 0.01, ecgQualityTier: 2,
                                               coherence: coherence, sdnn: sdnn, lfHF: lfHF))
            }
        }
        return out
    }
