    static func points() -> [MetricsHistoryPoint] {
        var comps = DateComponents(year: 2026, month: 8, day: 18)
        comps.hour = 12
        comps.minute = 30
        let start = Calendar.current.date(from: comps)!
        var out: [MetricsHistoryPoint] = []
        for (mins, hr, motion, coherence, lfHF, sdnn, rmssd) in samples {
            for tick in 0..<10 {
                let t = start.addingTimeInterval(Double(mins) * 60 + Double(tick) * 30)
                out.append(MetricsHistoryPoint(anchorTestTimestamp: t,
                                               meanBPM: hr, vti: log(rmssd),
                                               dc: 8, pip: 45, dfa1: 1.0,
                                               breathBPM: 13, motion: motion,
                                               signalQuality: 0.97,
                                               rrInvalidRate: 0.01, ecgQualityTier: 2,
                                               coherence: coherence, sdnn: sdnn, lfHF: lfHF))
            }
        }
        return out
    }
